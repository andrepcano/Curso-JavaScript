// craindo o objeto pessoa com as propriedades nome, sobrenome e idade
const pessoa = {
    nome: 'João',
    sobrenome: 'Silva',
    idade: 30,
};

console.log(pessoa.nome); // Acessando a propriedade 'nome' do objeto 'pessoa'
console.log(pessoa.sobrenome); // Acessando a propriedade 'sobrenome' do objeto 'pessoa'
console.log(pessoa.idade); // Acessando a propriedade 'idade' do objeto 'pessoa'